@pytest.mark.parametrize("name", REGIONS)
def test_each_generated_region_exists_exactly_once(report_text, name):
    assert report_text.count("<!-- BEGIN GENERATED: %s -->" % name) == 1
    assert report_text.count("<!-- END GENERATED: %s -->" % name) == 1


def test_every_marker_is_paired(report_text):
    begins = set(re.findall(r"<!-- BEGIN GENERATED: (\S+) -->", report_text))
    ends = set(re.findall(r"<!-- END GENERATED: (\S+) -->", report_text))
    assert begins == ends


