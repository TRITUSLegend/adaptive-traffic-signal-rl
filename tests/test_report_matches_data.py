"""
Tests that REPORT.md agrees with the data it describes.

WHY THESE TESTS EXIST
---------------------
This is defect D4 turned into a guard. The report used to claim that every
number in it was generated by `eval/make_tables.py` rather than transcribed by
hand. The claim was false: the generator only wrote a separate appendix file,
and the report's own tables were typed in. They happened to be accurate, but
nothing was checking - which is precisely the situation the claim was meant to
rule out. One re-run of the evaluation would have left the report quietly
describing numbers that no longer existed.

`make_tables.py --write` now splices the tables into REPORT.md between markers.
These tests close the loop from the other end: they read the numbers back OUT
of the committed report and check them against the CSVs, so the claim in §8 is
enforced rather than merely implemented.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from eval.make_tables import (  # noqa: E402
    LABELS,
    build,
    heuristic_table,
    insertion_backlog_table,
    read_raw,
    read_summary,
    report_wait_table,
)

REPORT = ROOT / "REPORT.md"
REGIONS = ["main-wait", "robustness-wait", "heuristic-vs-dqn",
           "insertion-backlog"]


@pytest.fixture(scope="module")
def report_text():
    if not REPORT.exists():
        pytest.skip("REPORT.md not present")
    return REPORT.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def summary():
    return read_summary()


@pytest.fixture(scope="module")
def raw():
    return read_raw()


def region(text: str, name: str) -> str:
    match = re.search(
        r"<!-- BEGIN GENERATED: %s -->\n(.*?)\n<!-- END GENERATED: %s -->"
        % (re.escape(name), re.escape(name)), text, re.S)
    assert match, "no generated region named %r in REPORT.md" % name
    return match.group(1)


