def summary_lookup(summary, controller, scenario, field):
    for row in summary:
        if row["controller"] == controller and row["scenario"] == scenario:
            return float(row[field])
    return None


@pytest.mark.parametrize("name,scenarios", [
    ("main-wait", ["balanced", "ns_heavy", "peak"]),
    ("robustness-wait", ["ew_heavy", "surge", "light"]),
])
def test_every_wait_cell_matches_the_summary_csv(report_text, summary, name,
                                                 scenarios):
    """
    Parsed straight out of the committed markdown, not re-rendered - so this
    would catch a hand edit to the report that the generator never made.
    """
    label_to_controller = {v: k for k, v in LABELS.items()}
    checked = 0
    for line in region(report_text, name).splitlines():
        if not line.startswith("| ") or line.startswith("|---") \
                or line.startswith("| Controller"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        controller = label_to_controller[cells[0].strip()]
        for scenario, cell in zip(scenarios, cells[1:]):
            numbers = re.findall(r"[\d.]+", cell.replace("**", ""))
            assert len(numbers) == 2, cell
            mean, sd = float(numbers[0]), float(numbers[1])
            # The table prints one decimal place, so compare against the CSV
            # value rounded the same way rather than with a tolerance - that
            # way a genuinely wrong digit cannot hide inside the slack.
            assert mean == round(summary_lookup(
                summary, controller, scenario, "mean_waiting_time_s_mean"), 1)
            assert sd == round(summary_lookup(
                summary, controller, scenario, "mean_waiting_time_s_std"), 1)
            checked += 1
    assert checked == len(scenarios) * 5, checked


def test_the_bolded_cell_really_is_the_best_in_its_column(report_text, summary):
    """Bold marks the lowest wait. If it drifted, it would mislead at a glance."""
    for name, scenarios in (("main-wait", ["balanced", "ns_heavy", "peak"]),
                            ("robustness-wait", ["ew_heavy", "surge", "light"])):
        rows = [ln for ln in region(report_text, name).splitlines()
                if ln.startswith("| ") and not ln.startswith("|---")
                and not ln.startswith("| Controller")]
        for column, scenario in enumerate(scenarios, start=1):
            bolded, values = [], []
            for line in rows:
                cells = [c.strip() for c in line.strip("|").split("|")]
                cell = cells[column]
                value = float(re.findall(r"[\d.]+", cell.replace("**", ""))[0])
                values.append(value)
                if cell.startswith("**"):
                    bolded.append(value)
            assert len(bolded) == 1, (scenario, bolded)
            assert bolded[0] == min(values), (scenario, bolded, min(values))


def test_the_appendix_file_is_current(summary):
    """results/logs/results_tables.md is the other half of `--write`."""
    path = ROOT / "results" / "logs" / "results_tables.md"
    if not path.exists():
        pytest.skip("results_tables.md not generated yet")
    assert path.read_text(encoding="utf-8") == build(summary)


